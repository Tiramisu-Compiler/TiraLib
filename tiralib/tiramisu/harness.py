# The wrapper is a single self-contained translation unit:
#   1. PolyBench compile-time options (POLYBENCH_TIME, ...)
#   2. vendored polybench.h + polybench.c, inlined verbatim
#   3. the per-benchmark init sidecar (PolyBench init_array/print_array,
#      extracted verbatim from PolyBench/C, operating on flat buffers)
#   4. a main() that runs each measurement in a freshly exec'ed process,
#      PolyBench-style: aligned alloc -> init_array -> cache flush + timer
#      start -> one kernel call -> timer stop -> print time.
# Being self-contained keeps it compatible with both wrapper build paths
# (CompilingService and TiraLibCpp's compile_wrapper) without flag changes.
