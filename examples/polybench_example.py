"""Measuring a PolyBench benchmark with the PolyBench-compatible harness.

The generator (`function_gemm_MINI_generator.cpp`) ships with an init
sidecar (`function_gemm_MINI_init.h`) generated by the
polybench-tiramisu repository. Its presence next to the generator makes
`TiramisuProgram.from_file` select the `PolybenchHarness`: each
measurement then follows PolyBench/C's methodology (deterministic
init_array, cache flush, one kernel invocation per fresh process), with
the kernel running on the OpenMP-backed runtime with bound threads
(schedule(static,1), OMP_PROC_BIND=close). Pass `runtime="halide"` to
the harness to keep Halide's own thread pool instead.
"""

from tiralib.config import BaseConfig
from tiralib.tiramisu import Schedule, TiramisuProgram, tiramisu_actions
from tiralib.tiramisu.harness import PolybenchHarness, polybench_normalized_time

BaseConfig.init()

program = TiramisuProgram.from_file(
    "./examples/function_gemm_MINI_generator.cpp",
    load_annotations=True,
    load_tree=True,
)
assert isinstance(program.harness, PolybenchHarness)  # auto-detected

schedule = Schedule(program)
schedule.add_optimizations([tiramisu_actions.Parallelization([("C_init", 0)])])

# 5 fresh-process measurements, PolyBench's time_benchmark.sh count
times_ms = schedule.execute(min_runs=5)
normalized, deviation_pct = polybench_normalized_time(times_ms)

print(f"times (ms): {times_ms}")
print(f"polybench-normalized: {normalized:.6f} ms (max deviation {deviation_pct:.2f}%)")
