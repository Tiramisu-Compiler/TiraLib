"""Measurement harnesses for TiraLib.

A harness owns the generation of the measurement *wrapper*: the standalone
binary that allocates and initializes the buffers, calls the compiled
Tiramisu function, measures its execution time, and prints the measured
times (in milliseconds) to stdout.

Two harnesses are provided:

- :class:`DefaultHarness` — TiraLib's historical harness: buffers are
  malloc'ed and filled once with a random constant, then the kernel is
  timed ``min_runs``/``max_runs`` times back-to-back in a single process
  with ``std::chrono``.

- :class:`PolybenchHarness` — a PolyBench/C 4.2.1 compatible harness for
  PolyBench-derived Tiramisu programs. Each measurement follows the exact
  PolyBench methodology, in a *fresh process* (like PolyBench's
  ``time_benchmark.sh``): page-aligned allocation via
  ``polybench_alloc_data``, deterministic PolyBench ``init_array``
  initialization (from a per-benchmark generated "init sidecar" header),
  cache flush before starting the timer (``polybench_timer_start``), one
  kernel invocation, ``polybench_timer_stop``. The vendored, unmodified
  PolyBench ``polybench.h``/``polybench.c`` sources are inlined into the
  generated wrapper, so the measurement code is PolyBench's own.

Both harnesses generate a self-contained wrapper that honors the same
execution protocol (``MIN_RUNS``/``MAX_RUNS``/``TIME_BUDGET`` environment
variables, one float per measurement in **milliseconds** on stdout), so
they are interchangeable for both the pure-Python backend
(``CompilingService``) and the TiraLibCpp server backend.
"""

from __future__ import annotations

import logging
import random
import re
from abc import ABC, abstractmethod
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from tiralib.tiramisu.tiramisu_program import TiramisuProgram

logger = logging.getLogger(__name__)

_POLYBENCH_DIR = Path(__file__).parent / "polybench"

#: Maps Tiramisu primitive type names to C types (as used by the
#: PolyBench reference implementations).
P_TYPE_TO_CTYPE = {
    "p_float64": "double",
    "p_float32": "float",
    "p_int32": "int",
    "p_int64": "long long",
    "p_uint8": "unsigned char",
    "p_uint16": "unsigned short",
    "p_uint32": "unsigned int",
    "p_int8": "signed char",
    "p_int16": "short",
}


class Harness(ABC):
    """Strategy object that generates the measurement wrapper code."""

    name: str = "abstract"

    @abstractmethod
    def generate_wrappers(self, program: "TiramisuProgram") -> dict[str, str]:
        """Return ``{"cpp": ..., "h": ...}`` wrapper sources for `program`."""


class DefaultHarness(Harness):
    """TiraLib's historical harness (random init, warm in-process timing)."""

    name = "default"

    def generate_wrappers(self, program: "TiramisuProgram") -> dict[str, str]:
        buffers_init_lines = ""
        for i, buffer_name in enumerate(program.IO_buffer_names):
            size_expr = "*".join(program.buffer_sizes[i][::-1])
            dims_expr = ",".join(program.buffer_sizes[i][::-1])
            buffers_init_lines += f"""
    double *c_{buffer_name} = (double*)malloc({size_expr}* sizeof(double));
    parallel_init_buffer(c_{buffer_name}, {size_expr}, (double){str(random.randint(1, 10))});
    Halide::Buffer<double> {buffer_name}(c_{buffer_name}, {dims_expr});
    """  # noqa: E501

        wrapper_cpp_code = wrapper_cpp_template.replace(
            "$func_id$", program.temp_files_identifier
        ).replace("$func_name$", program.name)
        wrapper_cpp_code = wrapper_cpp_code.replace(
            "$buffers_init$", buffers_init_lines
        )
        wrapper_cpp_code = wrapper_cpp_code.replace(
            "$func_params$",
            ",".join([name + ".raw_buffer()" for name in program.IO_buffer_names]),
        )

        wrapper_h_code = wrapper_h_template.replace("$func_name$", program.name)
        wrapper_h_code = wrapper_h_code.replace(
            "$func_params$",
            ",".join(["halide_buffer_t *" + name for name in program.IO_buffer_names]),
        )

        return {
            "cpp": wrapper_cpp_code,
            "h": wrapper_h_code,
        }


class PolybenchHarness(Harness):
    """PolyBench/C 4.2.1 compatible measurement harness.

    Parameters
    ----------
    `init_sidecar_path` : str | Path
        Path to the per-benchmark init sidecar header (generated by
        ``polybench_tiramisu``'s ``generate_polybench_init_sidecars.py``).
        The sidecar must define::

            static void tiralib_polybench_init_arrays(<typed buffer ptrs>);
            static void tiralib_polybench_dump_arrays(<typed buffer ptrs>);

        taking the program's I/O buffers (flat pointers) in
        ``tiramisu::codegen`` order.
    `cache_size_kb` : int | None
        Cache size flushed before each measurement, in kB. ``None`` keeps
        PolyBench's default (``POLYBENCH_CACHE_SIZE_KB`` = 32770, ~33MB).
    `flush_cache` : bool
        If False, defines ``POLYBENCH_NO_FLUSH_CACHE`` (PolyBench flushes
        by default).
    `linux_fifo_scheduler` : bool
        If True, defines ``POLYBENCH_LINUX_FIFO_SCHEDULER`` (requires
        running as root, see PolyBench documentation).

    Notes
    -----
    Measurement semantics under this harness:

    - ``min_runs``/``max_runs`` count *process-level* measurements: each
      measurement runs in a freshly exec'ed process (PolyBench runs one
      kernel per process; ``time_benchmark.sh`` re-runs the binary).
    - ``time_budget`` (ms) is enforced between measurements after the
      first ``min_runs``; a measurement in flight past the budget is
      killed (its time is discarded), matching the default harness.
    - Times are printed in **milliseconds** (TiraLib's unit convention)
      computed as ``(polybench_t_end - polybench_t_start) * 1000``; the
      timer itself is PolyBench's own (``gettimeofday``-based
      ``rtclock``, preceded by the PolyBench cache flush).
    - Setting the ``TIRALIB_DUMP_ARRAYS`` environment variable makes the
      first measurement dump the live-out arrays to stderr in PolyBench's
      ``POLYBENCH_DUMP_ARRAYS`` format (for correctness checking against
      the reference PolyBench/C implementation).
    """

    name = "polybench"

    def __init__(
        self,
        init_sidecar_path: str | Path | None = None,
        cache_size_kb: int | None = None,
        flush_cache: bool = True,
        linux_fifo_scheduler: bool = False,
        *,
        init_sidecar_code: str | None = None,
    ):
        if (init_sidecar_path is None) == (init_sidecar_code is None):
            raise ValueError(
                "PolybenchHarness requires exactly one of init_sidecar_path "
                "or init_sidecar_code"
            )
        self.cache_size_kb = cache_size_kb
        self.flush_cache = flush_cache
        self.linux_fifo_scheduler = linux_fifo_scheduler

        if init_sidecar_path is not None:
            self.init_sidecar_path = Path(init_sidecar_path)
            if not self.init_sidecar_path.exists():
                raise FileNotFoundError(
                    f"PolybenchHarness init sidecar not found: {self.init_sidecar_path}"
                )
            sidecar_code = self.init_sidecar_path.read_text()
            origin = str(self.init_sidecar_path)
        else:
            self.init_sidecar_path = None
            assert init_sidecar_code is not None
            sidecar_code = init_sidecar_code
            origin = "<in-memory sidecar>"

        for required in (
            "tiralib_polybench_init_arrays",
            "tiralib_polybench_dump_arrays",
        ):
            if required not in sidecar_code:
                raise ValueError(
                    f"Init sidecar {origin} does not define "
                    f"'{required}'. Was it generated by "
                    "generate_polybench_init_sidecars.py?"
                )
        self.sidecar_code = sidecar_code

    @classmethod
    def from_code(cls, init_sidecar_code: str, **options) -> "PolybenchHarness":
        """Build a harness from sidecar *content* rather than a file path.

        Useful when the benchmark sources come from an archive (e.g. the
        sidecar was read out of a zip next to the generator .cpp).
        `options` are forwarded to the constructor (cache_size_kb, ...).
        """
        return cls(init_sidecar_code=init_sidecar_code, **options)

    @classmethod
    def detect(
        cls, generator_file_path: str | Path, function_name: str
    ) -> "PolybenchHarness | None":
        """Detect a sidecar next to a generator file.

        Returns a :class:`PolybenchHarness` if
        ``<generator dir>/<function_name>_init.h`` exists, else None.
        """
        sidecar = Path(generator_file_path).parent / f"{function_name}_init.h"
        if sidecar.exists():
            logger.info(
                "PolyBench init sidecar found (%s): using PolybenchHarness",
                sidecar,
            )
            return cls(sidecar)
        return None

    def _polybench_sources(self) -> tuple[str, str]:
        polybench_h = (_POLYBENCH_DIR / "polybench.h").read_text()
        polybench_c = (_POLYBENCH_DIR / "polybench.c").read_text()
        # The sources are inlined into a single translation unit: drop the
        # self-include (everything it needs is pasted right above it).
        polybench_c = re.sub(
            r'#\s*include\s+"polybench\.h"',
            "// (polybench.h inlined above)",
            polybench_c,
        )
        return polybench_h, polybench_c

    def _buffer_ctypes(self, program: "TiramisuProgram") -> list[str]:
        p_types = getattr(program, "buffer_types", None)
        if not p_types:
            p_types = ["p_float64"] * len(program.IO_buffer_names)
        ctypes = []
        for p_type in p_types:
            if p_type not in P_TYPE_TO_CTYPE:
                raise ValueError(f"PolybenchHarness: unsupported buffer type {p_type}")
            ctypes.append(P_TYPE_TO_CTYPE[p_type])
        return ctypes

    def generate_wrappers(self, program: "TiramisuProgram") -> dict[str, str]:
        polybench_h, polybench_c = self._polybench_sources()
        ctypes = self._buffer_ctypes(program)

        defines = ["#define POLYBENCH_TIME 1"]
        if self.cache_size_kb is not None:
            defines.append(f"#define POLYBENCH_CACHE_SIZE_KB {self.cache_size_kb}")
        if not self.flush_cache:
            defines.append("#define POLYBENCH_NO_FLUSH_CACHE 1")
        if self.linux_fifo_scheduler:
            defines.append("#define POLYBENCH_LINUX_FIFO_SCHEDULER 1")

        buffers_decl = ""
        buffers_free = ""
        for name, sizes, ctype in zip(
            program.IO_buffer_names, program.buffer_sizes, ctypes
        ):
            size_expr = "*".join(sizes)
            # Halide dims are innermost-first: reverse the declared sizes.
            dims_expr = ",".join(sizes[::-1])
            buffers_decl += (
                f"    {ctype} *c_{name} = ({ctype}*) polybench_alloc_data"
                f"({size_expr}, sizeof({ctype}));\n"
                f"    Halide::Buffer<{ctype}> {name}(c_{name}, {dims_expr});\n"
            )
            buffers_free += f"    free((void*)c_{name});\n"

        c_ptr_args = ", ".join(f"c_{name}" for name in program.IO_buffer_names)
        func_params = ",".join(
            name + ".raw_buffer()" for name in program.IO_buffer_names
        )

        wrapper_cpp_code = (
            polybench_wrapper_cpp_template.replace(
                "$polybench_defines$", "\n".join(defines)
            )
            .replace("$polybench_h$", polybench_h)
            .replace("$polybench_c$", polybench_c)
            .replace("$init_sidecar$", self.sidecar_code)
            .replace("$func_id$", program.temp_files_identifier)
            .replace("$func_name$", program.name)
            .replace("$buffers_decl$", buffers_decl)
            .replace("$buffers_free$", buffers_free)
            .replace("$c_ptr_args$", c_ptr_args)
            .replace("$func_params$", func_params)
        )

        wrapper_h_code = polybench_wrapper_h_template.replace(
            "$func_name$", program.name
        ).replace(
            "$func_params$",
            ",".join("halide_buffer_t *" + name for name in program.IO_buffer_names),
        )

        return {
            "cpp": wrapper_cpp_code,
            "h": wrapper_h_code,
        }


def polybench_normalized_time(
    times: list[float], variance_accepted: float = 5.0
) -> tuple[float, float]:
    """Normalize measurements the way PolyBench's ``time_benchmark.sh`` does.

    Sorts the measurements, discards the smallest and largest, and returns
    the arithmetic mean of the remaining ones together with the maximal
    deviation from that mean in percent. PolyBench runs the benchmark 5
    times and averages the middle 3; pass 5 measurements to reproduce that
    exactly.

    Logs a warning (like the script) if the deviation exceeds
    `variance_accepted` percent.

    Returns
    -------
    ``(normalized_time, max_deviation_percent)``
    """
    if len(times) < 3:
        raise ValueError(
            "polybench_normalized_time needs at least 3 measurements "
            f"(got {len(times)}); PolyBench uses 5"
        )
    middle = sorted(times)[1:-1]
    mean = sum(middle) / len(middle)
    max_dev = max(abs(t - mean) for t in middle)
    variance = (max_dev / mean) * 100 if mean != 0 else 0.0
    if variance >= variance_accepted:
        logger.warning(
            "Variance is above threshold, unsafe performance measurement "
            "=> max deviation=%.5f%%, tolerance=%s%%",
            variance,
            variance_accepted,
        )
    return mean, variance


